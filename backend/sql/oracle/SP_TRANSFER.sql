-- 참고용: 은행 레거시에서 흔한 "비즈니스 로직을 저장 프로시저에 위임" 패턴 예시 (Oracle).
-- 이 프로젝트의 AccountServiceImpl.transfer() 와 동일한 업무를 PL/SQL 로 구현한 것.
-- MyBatis 에서는 <update id="callTransfer" statementType="CALLABLE"> 로 호출한다.
CREATE OR REPLACE PROCEDURE SP_TRANSFER (
    P_FROM_ACCT  IN  VARCHAR2,
    P_TO_ACCT    IN  VARCHAR2,
    P_AMOUNT     IN  NUMBER,
    P_MEMO       IN  VARCHAR2,
    P_RESULT_CD  OUT VARCHAR2,
    P_RESULT_MSG OUT VARCHAR2
) IS
    V_FROM_BAL TB_ACCOUNT.BALANCE%TYPE;
    V_TO_BAL   TB_ACCOUNT.BALANCE%TYPE;
BEGIN
    -- 데드락 방지: 계좌번호 순으로 잠금
    FOR R IN (SELECT ACCT_NO FROM TB_ACCOUNT
               WHERE ACCT_NO IN (P_FROM_ACCT, P_TO_ACCT)
               ORDER BY ACCT_NO FOR UPDATE) LOOP
        NULL;
    END LOOP;

    SELECT BALANCE INTO V_FROM_BAL FROM TB_ACCOUNT WHERE ACCT_NO = P_FROM_ACCT;
    IF V_FROM_BAL < P_AMOUNT THEN
        P_RESULT_CD  := 'E102';
        P_RESULT_MSG := '잔액이 부족합니다.';
        RETURN;
    END IF;

    UPDATE TB_ACCOUNT SET BALANCE = BALANCE - P_AMOUNT WHERE ACCT_NO = P_FROM_ACCT;
    UPDATE TB_ACCOUNT SET BALANCE = BALANCE + P_AMOUNT WHERE ACCT_NO = P_TO_ACCT;

    SELECT BALANCE INTO V_TO_BAL FROM TB_ACCOUNT WHERE ACCT_NO = P_TO_ACCT;

    INSERT INTO TB_TRANS_HIST (TRANS_SEQ, ACCT_NO, TRANS_TP, AMOUNT, BALANCE_AFTER, COUNTER_ACCT_NO, MEMO)
    VALUES (SEQ_TRANS_HIST.NEXTVAL, P_FROM_ACCT, 'W', P_AMOUNT, V_FROM_BAL - P_AMOUNT, P_TO_ACCT, P_MEMO);
    INSERT INTO TB_TRANS_HIST (TRANS_SEQ, ACCT_NO, TRANS_TP, AMOUNT, BALANCE_AFTER, COUNTER_ACCT_NO, MEMO)
    VALUES (SEQ_TRANS_HIST.NEXTVAL, P_TO_ACCT, 'D', P_AMOUNT, V_TO_BAL, P_FROM_ACCT, P_MEMO);

    P_RESULT_CD  := '0000';
    P_RESULT_MSG := '정상 처리되었습니다.';
EXCEPTION
    WHEN OTHERS THEN
        P_RESULT_CD  := 'E999';
        P_RESULT_MSG := SQLERRM;
END SP_TRANSFER;
