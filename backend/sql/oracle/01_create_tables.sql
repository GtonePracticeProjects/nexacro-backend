-- Oracle 12c+ / 앱 계정(BANK_NX) 스키마에서 실행 (SQL Developer: F5 "스크립트 실행")
-- 재실행이 필요하면 먼저 00_drop_all.sql 실행

-- 1. 계좌
CREATE TABLE TB_ACCOUNT (
    ACCT_NO     VARCHAR2(20)   NOT NULL,
    CUST_NM     VARCHAR2(50)   NOT NULL,
    BALANCE     NUMBER(18,0)   DEFAULT 0 NOT NULL,
    STATUS_CD   CHAR(1)        DEFAULT 'A' NOT NULL,   -- A:정상, C:해지
    REG_DT      DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_ACCOUNT PRIMARY KEY (ACCT_NO),
    CONSTRAINT CK_TB_ACCOUNT_BAL CHECK (BALANCE >= 0)
);
COMMENT ON TABLE  TB_ACCOUNT           IS '계좌';
COMMENT ON COLUMN TB_ACCOUNT.STATUS_CD IS 'A:정상, C:해지';

-- 2. 거래내역
CREATE SEQUENCE SEQ_TRANS_HIST START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_TRANS_HIST (
    TRANS_SEQ        NUMBER(18,0)   NOT NULL,
    ACCT_NO          VARCHAR2(20)   NOT NULL,
    TRANS_TP         CHAR(1)        NOT NULL,           -- W:출금, D:입금
    AMOUNT           NUMBER(18,0)   NOT NULL,
    BALANCE_AFTER    NUMBER(18,0)   NOT NULL,
    COUNTER_ACCT_NO  VARCHAR2(20),
    MEMO             VARCHAR2(100),
    TRANS_DT         DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_TRANS_HIST PRIMARY KEY (TRANS_SEQ),
    CONSTRAINT FK_TRANS_ACCT FOREIGN KEY (ACCT_NO) REFERENCES TB_ACCOUNT (ACCT_NO),
    CONSTRAINT CK_TRANS_TP CHECK (TRANS_TP IN ('W', 'D'))
);
CREATE INDEX IDX_TRANS_HIST_01 ON TB_TRANS_HIST (ACCT_NO, TRANS_DT);

-- 3. 고객
CREATE SEQUENCE SEQ_CUSTOMER START WITH 4 INCREMENT BY 1 NOCACHE;  -- 샘플 3건 이후부터

CREATE TABLE TB_CUSTOMER (
    CUST_NO   VARCHAR2(10)  NOT NULL,                   -- 'C' + 6자리 (C000001)
    CUST_NM   VARCHAR2(50)  NOT NULL,
    PHONE     VARCHAR2(20),
    EMAIL     VARCHAR2(100),
    REG_DT    DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_CUSTOMER PRIMARY KEY (CUST_NO)
);

-- 4. 대출
CREATE SEQUENCE SEQ_LOAN START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_LOAN (
    LOAN_NO      NUMBER(18,0)  NOT NULL,
    ACCT_NO      VARCHAR2(20)  NOT NULL,
    PRINCIPAL    NUMBER(18,0)  NOT NULL,
    RATE         NUMBER(5,2)   NOT NULL,
    TERM_MONTHS  NUMBER(3,0)   NOT NULL,
    MONTHLY_PAY  NUMBER(18,0)  NOT NULL,
    STATUS_CD    CHAR(1)       DEFAULT 'R' NOT NULL,    -- R:신청, A:승인, X:거절
    REQ_DT       DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_LOAN PRIMARY KEY (LOAN_NO),
    CONSTRAINT FK_LOAN_ACCT FOREIGN KEY (ACCT_NO) REFERENCES TB_ACCOUNT (ACCT_NO),
    CONSTRAINT CK_LOAN_STATUS CHECK (STATUS_CD IN ('R', 'A', 'X'))
);
CREATE INDEX IDX_LOAN_01 ON TB_LOAN (STATUS_CD, LOAN_NO);

-- 5. 공지사항
CREATE SEQUENCE SEQ_NOTICE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_NOTICE (
    NOTICE_SEQ  NUMBER(18,0)    NOT NULL,
    TITLE       VARCHAR2(200)   NOT NULL,
    CONTENT     VARCHAR2(4000),
    WRITER      VARCHAR2(50)    NOT NULL,
    VIEW_CNT    NUMBER(9,0)     DEFAULT 0 NOT NULL,
    REG_DT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TB_NOTICE PRIMARY KEY (NOTICE_SEQ)
);
